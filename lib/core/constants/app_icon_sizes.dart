/// Centralized semantic icon sizes for Shoppy.
/// Ensures visual balance, hierarchy, and consistency across all screens.
abstract final class AppIconSizes {
  // Base scale
  static const double xs = 12.0;
  static const double sm = 16.0;
  static const double md = 20.0;
  static const double lg = 24.0;
  static const double xl = 28.0;
  static const double xxl = 32.0;
  static const double hero = 48.0;
  static const double emptyState = 64.0;

  // Semantic names explicitly defined for the design system
  static const double small = sm;
  static const double medium = md;
  static const double large = lg;
  static const double navigation = lg;
  static const double button = sm;
  static const double productAction = sm;
  static const double avatarAction = sm;
  static const double badge = xs;
  static const double rating = 14.0;
  static const double action = 18.0;
  static const double display = 36.0;
}
